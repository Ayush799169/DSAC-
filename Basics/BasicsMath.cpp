#include <iostream>
#include <cmath>
using namespace std;
int main() {
    double x = 9.0;
    double y = sqrt(x); // Calculate the square root of x
    double z = pow(x, 2); // Calculate x raised to the power of 2
    cout << "The square root of " << x << " is " << y << endl;
    cout << x << " raised to the power of 2 is " << z << endl;
    return 0;
}